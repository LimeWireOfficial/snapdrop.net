const peerBack = () => {
  transfers.forEach((tr) => {
    if (tr.ended || !tr.away) return;
    const peer = findPeer({ id: tr.peerId, name: tr.peerName, platform: tr.peerPlatform, pk: tr.peerPk });
    if (!peer) return;
    tr.peerId = peer.id;
    clearTimeout(tr.awayTimer);
    tr.away = 0;
    ga('p2p_peer_back', { role: tr.role, size: sizeBucket(tr.total) });
    if (tr.role === 'send') reoffer(tr);
    else drawCard(tr);
  });
};

const reoffer = (tr) => {
  if (tr.ended) return;
  if (tr.round >= MAX_ROUNDS) { broken(tr, tr.resuming ? 'channel_closed' : 'peer_left'); return; }
  dropPc(tr);
  tr.round += 1;
  tr.waitAccept = true;
  if (!tr.resuming) tr.state = 'offer';
  const ok = signal(tr.peerId, tr.resuming ? { t: 'resume', tid: tr.tid, rd: tr.round } : offerMsg(tr));
  drawCard(tr);
  if (!ok) peerAway(tr);
};



const lost = (tr) => {
  if (tr.ended) return;
  if (!tr.canResume || (tr.resumes || 0) >= MAX_RESUMES) { broken(tr, 'channel_closed'); return; }
  tr.resumes = (tr.resumes || 0) + 1;
  
  
  if (tr.role === 'recv') signal(tr.peerId, { t: 'lost', tid: tr.tid, rd: tr.round });
  dropPc(tr);
  tr.resuming = Date.now();
  tr.resumeWait = false;
  tr.state = 'connecting';
  clearTimeout(tr.resumeTimer);
  tr.resumeTimer = setTimeout(() => broken(tr, 'channel_closed'), RESUME_MS);
  ga('p2p_resume_start', { role: tr.role, size: sizeBucket(tr.total) });
  if (tr.role === 'send') reoffer(tr);
  else drawCard(tr);
};

