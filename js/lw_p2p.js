const finish = (tr, result, reason) => {
  if (tr.ended) return;
  tr.ended = true;
  tr.result = result;
  tr.reason = reason;
  clearTimeout(tr.timer);
  clearTimeout(tr.slowTimer);
  clearTimeout(tr.awayTimer);
  clearTimeout(tr.resumeTimer);
  tr.away = 0;
  tr.resuming = 0;
  tr.state = result === 'completed' ? 'done' : result;
  const closeLater = () => {
    try { if (tr.dc) tr.dc.close(); } catch (e) {   }
    try { if (tr.pc) tr.pc.close(); } catch (e) {   }
  };
  
  if (result === 'completed' && tr.role === 'recv') setTimeout(closeLater, 1500); else closeLater();
  if (tr.role === 'send') {
    stat(result, reason, sizeBucket(tr.total), tr.via);
    if (result === 'completed') {
      const seconds = Math.max(0.001, (Date.now() - (tr.startedAt || Date.now())) / 1000);
      ga('p2p_transfer_completed', { size: sizeBucket(tr.total), file_count: tr.count, mbps: Math.round((tr.total / MB / seconds) * 10) / 10 });
    } else if (result === 'failed') {
      ga('p2p_transfer_failed', { reason, size: sizeBucket(tr.total), hidden: tr.wentHidden ? 1 : 0 });
    }
  } else if (result === 'failed') {
    ga('p2p_receive_failed', { reason, size: sizeBucket(tr.total) });
  }
  releaseWake();
  drawCard(tr);
  paintPeerProgress(tr);
  if (result === 'completed') flashDone(tr.peerId);
};

 




