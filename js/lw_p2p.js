const onServerMessage = (msg) => {
  switch (msg.type) {
    case 'welcome':
      retry = 0;
      me = msg.you;
      crowded = !!msg.crowded;
      iceServers = (msg.rtc && Array.isArray(msg.rtc.iceServers)) ? msg.rtc.iceServers : [];
      state = 'ready';
      rejoined = readyReported;
      if (!readyReported) {
        readyReported = true;
        ga('p2p_ready', { crowded: crowded ? 1 : 0, in_app: IN_APP ? 1 : 0 });
      }
      joinFromHash();
      pairView.update();
      break;
    case 'peers': {
      peers.clear();
      (msg.peers || []).forEach(addPeer);
      
      
      
      const fresh = rejoined;
      rejoined = false;
      transfers.forEach((tr) => {
        if (tr.ended || tr.dcOpen) return;
        if (!peers.has(tr.peerId)) peerAway(tr);
        else if (fresh && tr.role === 'send' && !tr.away) reoffer(tr);
      });
      peerBack();
      renderPeers();
      break;
    }
    case 'peer-joined':
      addPeer(msg.peer);
      peerBack();
      renderPeers();
      break;
    case 'peer-left':
      peers.delete(msg.id);
      transfers.forEach((tr) => { if (tr.peerId === msg.id && !tr.dcOpen) peerAway(tr); });
      renderPeers();
      break;
    case 'peer-renamed': {
      const peer = peers.get(msg.id);
      if (peer) {
        peer.name = String(msg.name || peer.name).slice(0, 40);
        if (peer.pk) savePair(peer.pk, peer.name);
        renderPeers();
      }
      break;
    }
    case 'pair-code':
      pairView.code(msg.code, msg.expiresAt);
      break;
    case 'paired':
      savePair(msg.key, msg.peer && msg.peer.name);
      addPeer(msg.peer);
      renderPeers();
      pairView.close();
      toast(t('pair_done', { name: (msg.peer && msg.peer.name) || '' }));
      ga('p2p_pair_completed', {});
      break;
    case 'pair-error':
      pairView.error(msg.error);
      break;
    case 'pair-request':
      pairAsk.show(msg.rid, msg.peer);
      break;
    case 'pair-request-gone':
      pairAsk.gone(msg.rid);
      break;
    case 'pair-pending':
      pairView.pending(msg.peer);
      break;
    case 'signal':
      onPeerSignal(msg.from, msg.data);
      break;
    case 'error':
      if (msg.error === 'peer_unavailable') {
        transfers.forEach((tr) => { if (tr.peerId === msg.to && !tr.dcOpen) peerAway(tr); });
      }
      break;
    default:
      break;
  }
};

 

