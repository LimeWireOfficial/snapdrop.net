const lockDevice = (steal) => {
  const queue = steal ? null : new AbortController();
  if (queue) tabQueue = queue;
  let held = false;
  navigator.locks.request(TAB_LOCK, steal ? { steal: true } : { signal: queue.signal }, (lock) => {
    if (queue && tabQueue === queue) tabQueue = null;
    
    if (!lock || tabRelease) return null;
    held = true;
    
    
    if (tabQueue) { tabQueue.abort(); tabQueue = null; }
    return new Promise((resolve) => {
      tabRelease = resolve;
      takeDevice();
    });
  }).catch(() => {
    if (queue && tabQueue === queue) tabQueue = null;
    
    if (held && tabRelease) { dropDevice(); queueDevice(); }
  });
};


const queueDevice = () => {
  if (!tabBus || tabRelease || tabQueue) return;
  lockDevice(false);
};

const yieldDevice = () => {
  const release = tabRelease;
  if (!release) return;
  dropDevice();
  release();
  queueDevice();
};

function claimDevice() {
  if (!tabBus) { connect(); return; }
  if (tabRelease) return;
  
  queueDevice();
  tabBus.postMessage({ t: 'claim' });
  clearTimeout(tabSleepTimer);
  tabSleepTimer = setTimeout(() => {
    if (tabRelease || state === 'elsewhere') return;
    state = 'elsewhere';
    renderPeers();
  }, 700);
  clearTimeout(tabStealTimer);
  tabStealTimer = setTimeout(() => {
    if (tabRelease || tabBusy) return;
    lockDevice(true);
  }, 1500);
}

